-- ============================================================
--  Smart Weather - Tache INTERVENTION (Oracle 11g XE)
--  A executer avec METEO5 / meteo5 (SQL Developer : F5 = "Executer le script").
--
--  MODELE PHYSIQUE : exactement 5 tables, AUCUNE table d'historique.
--
--      ZONE ----------< INTERVENTION >---------- AGENT       (Possede / Affect)
--      ZONE ----------< AGENT                                (Possede)
--      EQUIPEMENT ------< INTERVENTION                       (Utilise)
--      FOURNISSEUR -----< EQUIPEMENT                         (Fournit)
--
--  IMPORTANT : toutes les valeurs stockees (statuts, types, roles...) sont
--  ECRITES SANS ACCENT. Cela supprime le probleme "PlanifiÃ©e" : l'application
--  affiche les accents elle-meme, la base ne contient que de l'ASCII.
--
--  Le script est re-executable : il supprime puis recree les 5 tables
--  (et supprime aussi l'ancienne table INTERVENTION_EQUIPEMENT et toute
--  table *HISTOR*). Les donnees existantes sont remplacees par la demo.
-- ============================================================
SET DEFINE OFF

-- ---------- Nettoyage ----------
BEGIN
  FOR t IN (SELECT table_name FROM user_tables
            WHERE table_name IN ('INTERVENTION_EQUIPEMENT','INTERVENTION','AGENT','EQUIPEMENT','FOURNISSEUR','ZONE')
               OR table_name LIKE '%HISTOR%') LOOP
    EXECUTE IMMEDIATE 'DROP TABLE '||t.table_name||' CASCADE CONSTRAINTS PURGE';
  END LOOP;
  FOR s IN (SELECT sequence_name FROM user_sequences
            WHERE sequence_name IN ('SEQ_ZONE','SEQ_AGENT','SEQ_EQUIPEMENT','SEQ_FOURNISSEUR','SEQ_INTERVENTION')
               OR sequence_name LIKE '%HISTOR%') LOOP
    EXECUTE IMMEDIATE 'DROP SEQUENCE '||s.sequence_name;
  END LOOP;
END;
/

CREATE SEQUENCE SEQ_ZONE         START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_FOURNISSEUR  START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_EQUIPEMENT   START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_AGENT        START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_INTERVENTION START WITH 1 INCREMENT BY 1 NOCACHE;

-- ---------- 1/5 ZONE ----------
CREATE TABLE ZONE (
  ID_ZONE       NUMBER(10)    NOT NULL,
  NOM           VARCHAR2(100) NOT NULL,
  CODE          VARCHAR2(20)  NOT NULL,
  VULNERABILITE NUMBER(4,1)   DEFAULT 0 NOT NULL,
  LATITUDE      NUMBER(9,6)   DEFAULT 36.8065 NOT NULL,
  LONGITUDE     NUMBER(9,6)   DEFAULT 10.1815 NOT NULL,
  STATUT        VARCHAR2(10)  DEFAULT 'Active' NOT NULL,
  CONSTRAINT PK_ZONE        PRIMARY KEY (ID_ZONE),
  CONSTRAINT CK_ZONE_VULN   CHECK (VULNERABILITE BETWEEN 0 AND 100),
  CONSTRAINT CK_ZONE_STATUT CHECK (STATUT IN ('Active','Inactive'))
);
CREATE UNIQUE INDEX UQ_ZONE_CODE ON ZONE (UPPER(CODE));

-- ---------- 2/5 FOURNISSEUR ----------
CREATE TABLE FOURNISSEUR (
  ID_FOURNISSEUR   NUMBER(10)    NOT NULL,
  NOM              VARCHAR2(100) NOT NULL,
  TYPE             VARCHAR2(50)  NOT NULL,
  CONTACT          VARCHAR2(100),
  EMAIL            VARCHAR2(100),
  TELEPHONE        VARCHAR2(30),
  ADRESSE          VARCHAR2(200),
  MATRICULE_FISCAL VARCHAR2(30),
  VILLE            VARCHAR2(50),
  GOUVERNORAT      VARCHAR2(50),
  NOTE             NUMBER(1)     DEFAULT 3 NOT NULL,
  DELAI            NUMBER(3)     DEFAULT 7 NOT NULL,
  DATE_DEBUT       DATE          NOT NULL,
  DATE_FIN         DATE          NOT NULL,
  STATUT           VARCHAR2(20)  DEFAULT 'Actif' NOT NULL,
  CONSTRAINT PK_FOURNISSEUR  PRIMARY KEY (ID_FOURNISSEUR),
  CONSTRAINT CK_FOURN_TYPE   CHECK (TYPE IN ('Capteurs et stations','Maintenance','Energie','Reseau et telecom','Informatique')),
  CONSTRAINT CK_FOURN_NOTE   CHECK (NOTE BETWEEN 1 AND 5),
  CONSTRAINT CK_FOURN_DELAI  CHECK (DELAI BETWEEN 1 AND 365),
  CONSTRAINT CK_FOURN_DATES  CHECK (DATE_FIN >= DATE_DEBUT),
  CONSTRAINT CK_FOURN_STATUT CHECK (STATUT IN ('Actif','Suspendu','Archive'))
);

-- ---------- 3/5 EQUIPEMENT  (FOURNISSEUR 1 --- 0,N EQUIPEMENT : "Fournit") ----------
CREATE TABLE EQUIPEMENT (
  ID_EQUIPEMENT  NUMBER(10)    NOT NULL,
  NOM            VARCHAR2(100) NOT NULL,
  CODE           VARCHAR2(20),
  CATEGORIE      VARCHAR2(50)  NOT NULL,
  STATUT         VARCHAR2(30)  DEFAULT 'Disponible' NOT NULL,
  LOCALISATION   VARCHAR2(100) NOT NULL,
  DERNIERE_MAINT DATE,
  DESCRIPTION    VARCHAR2(500),
  ID_FOURNISSEUR NUMBER(10),
  CONSTRAINT PK_EQUIPEMENT        PRIMARY KEY (ID_EQUIPEMENT),
  CONSTRAINT CK_EQUIPEMENT_CAT    CHECK (CATEGORIE IN ('Capteurs','Vehicules','Materiel de terrain','Equipements de securite')),
  CONSTRAINT CK_EQUIPEMENT_STATUT CHECK (STATUT IN ('Disponible','En maintenance','Hors service')),
  CONSTRAINT FK_EQUIPEMENT_FOURN  FOREIGN KEY (ID_FOURNISSEUR) REFERENCES FOURNISSEUR(ID_FOURNISSEUR) ON DELETE SET NULL
);
CREATE UNIQUE INDEX UQ_EQUIPEMENT_CODE ON EQUIPEMENT (UPPER(CODE));
CREATE INDEX IDX_EQUIPEMENT_FOURN ON EQUIPEMENT(ID_FOURNISSEUR);

-- ---------- 4/5 AGENT  (ZONE 1 --- 0,N AGENT : "Possede") ----------
CREATE TABLE AGENT (
  ID_AGENT      NUMBER(10)    NOT NULL,
  NOM           VARCHAR2(100) NOT NULL,
  PRENOM        VARCHAR2(100) NOT NULL,
  ROLE          VARCHAR2(50)  NOT NULL,
  STATUT        VARCHAR2(20)  DEFAULT 'Disponible' NOT NULL,
  ID_ZONE       NUMBER(10),
  QUART_TRAVAIL VARCHAR2(30)  DEFAULT 'Matin' NOT NULL,
  EMAIL         VARCHAR2(100),
  TELEPHONE     VARCHAR2(30),
  CONSTRAINT PK_AGENT        PRIMARY KEY (ID_AGENT),
  CONSTRAINT CK_AGENT_ROLE   CHECK (ROLE IN ('Technicien Meteo','Meteorologue','Superviseur','Agent de terrain')),
  CONSTRAINT CK_AGENT_STATUT CHECK (STATUT IN ('En service','Disponible','En conge','Formation')),
  CONSTRAINT CK_AGENT_QUART  CHECK (QUART_TRAVAIL IN ('Matin','Apres-midi','Nuit')),
  CONSTRAINT FK_AGENT_ZONE   FOREIGN KEY (ID_ZONE) REFERENCES ZONE(ID_ZONE) ON DELETE SET NULL
);
CREATE INDEX IDX_AGENT_ZONE ON AGENT(ID_ZONE);

-- ---------- 5/5 INTERVENTION ----------
--   ZONE        1 --- 0,N INTERVENTION   (ID_ZONE)        "Possede"
--   AGENT       0,1 -- 0,N INTERVENTION  (ID_AGENT)       "Affect"
--   EQUIPEMENT  0,1 -- 0,N INTERVENTION  (ID_EQUIPEMENT)  "Utilise"
CREATE TABLE INTERVENTION (
  ID_INTERVENTION NUMBER(10)     NOT NULL,
  TYPE            VARCHAR2(50)   NOT NULL,
  PRIORITE        VARCHAR2(10)   DEFAULT 'Moyenne'   NOT NULL,
  STATUT          VARCHAR2(20)   DEFAULT 'Planifiee' NOT NULL,
  DATE_DEBUT      DATE           NOT NULL,
  DATE_FIN        DATE,
  DESCRIPTION     VARCHAR2(500),
  RESPONSABLE     VARCHAR2(100),
  COMPTE_RENDU    VARCHAR2(2000),
  ID_ZONE         NUMBER(10)     NOT NULL,
  ID_AGENT        NUMBER(10),
  ID_EQUIPEMENT   NUMBER(10),
  CONSTRAINT PK_INTERVENTION PRIMARY KEY (ID_INTERVENTION),
  CONSTRAINT CK_INTERV_TYPE   CHECK (TYPE IN ('Inondation','Chaleur','Vent fort','Maintenance station','Inspection','Autre')),
  CONSTRAINT CK_INTERV_PRIO   CHECK (PRIORITE IN ('Faible','Moyenne','Haute','Critique')),
  CONSTRAINT CK_INTERV_STATUT CHECK (STATUT IN ('Planifiee','En cours','Terminee','Annulee')),
  CONSTRAINT CK_INTERV_DATES  CHECK (DATE_FIN IS NULL OR DATE_FIN >= DATE_DEBUT),
  CONSTRAINT CK_INTERV_CLOT   CHECK (STATUT <> 'Terminee' OR NVL(LENGTH(TRIM(COMPTE_RENDU)),0) >= 20),
  CONSTRAINT FK_INTERV_ZONE   FOREIGN KEY (ID_ZONE)       REFERENCES ZONE(ID_ZONE),
  CONSTRAINT FK_INTERV_AGENT  FOREIGN KEY (ID_AGENT)      REFERENCES AGENT(ID_AGENT)           ON DELETE SET NULL,
  CONSTRAINT FK_INTERV_EQUIP  FOREIGN KEY (ID_EQUIPEMENT) REFERENCES EQUIPEMENT(ID_EQUIPEMENT) ON DELETE SET NULL
);
CREATE INDEX IDX_INTERV_ZONE  ON INTERVENTION(ID_ZONE);
CREATE INDEX IDX_INTERV_AGENT ON INTERVENTION(ID_AGENT);
CREATE INDEX IDX_INTERV_EQUIP ON INTERVENTION(ID_EQUIPEMENT);

-- ---------- Triggers : cle primaire automatique ----------
CREATE OR REPLACE TRIGGER TRG_ZONE_ID BEFORE INSERT ON ZONE FOR EACH ROW WHEN (NEW.ID_ZONE IS NULL)
BEGIN :NEW.ID_ZONE := SEQ_ZONE.NEXTVAL; END;
/
CREATE OR REPLACE TRIGGER TRG_FOURNISSEUR_ID BEFORE INSERT ON FOURNISSEUR FOR EACH ROW WHEN (NEW.ID_FOURNISSEUR IS NULL)
BEGIN :NEW.ID_FOURNISSEUR := SEQ_FOURNISSEUR.NEXTVAL; END;
/
CREATE OR REPLACE TRIGGER TRG_EQUIPEMENT_ID BEFORE INSERT ON EQUIPEMENT FOR EACH ROW WHEN (NEW.ID_EQUIPEMENT IS NULL)
BEGIN :NEW.ID_EQUIPEMENT := SEQ_EQUIPEMENT.NEXTVAL; END;
/
CREATE OR REPLACE TRIGGER TRG_AGENT_ID BEFORE INSERT ON AGENT FOR EACH ROW WHEN (NEW.ID_AGENT IS NULL)
BEGIN :NEW.ID_AGENT := SEQ_AGENT.NEXTVAL; END;
/
CREATE OR REPLACE TRIGGER TRG_INTERVENTION_ID BEFORE INSERT ON INTERVENTION FOR EACH ROW WHEN (NEW.ID_INTERVENTION IS NULL)
BEGIN :NEW.ID_INTERVENTION := SEQ_INTERVENTION.NEXTVAL; END;
/

